@pytest.mark.asyncio
async def test_post_messages_422_body_is_structured_json_without_traceback(
    api_client_with_inmemory_bus,
):
    """
    The 422 response body must be valid, structured JSON and must not expose
    Python stack traces or internal exception details.
    Prevents information leakage at the HTTP boundary (conventions §5).
    """
    client, _bus = api_client_with_inmemory_bus

    payload = {}  # completely empty — all required fields missing
    response = await client.post("/v1/messages", json=payload)

    assert response.status_code == 422
    data = response.json()
    assert isinstance(data, dict), "422 body must be a JSON object"

    body_text = str(data)
    assert "Traceback" not in body_text, "Stack trace must not appear in 422 response"
    assert "Exception" not in body_text, "Exception class must not appear in 422 response"
