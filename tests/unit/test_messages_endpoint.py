@pytest.mark.asyncio
async def test_post_messages_valid_body_returns_queued_status(api_client_with_inmemory_bus):
    """
    POST /v1/messages with a valid body must return HTTP 200 (or 202) and a
    JSON body containing status='queued'.
    This confirms the endpoint enqueues the task and responds immediately
    without waiting for processing (contracts.md §1.2, ADR-0003).
    """
    client, _bus = api_client_with_inmemory_bus

    payload = {
        "channel": "telegram",
        "channel_user_id": "12345",
        "text": "200г жареной курицы",
        "reply_to": {"chat_id": 99, "message_id": 7},
    }
    response = await client.post("/v1/messages", json=payload)

    assert response.status_code in (200, 202)
    data = response.json()
    assert data["status"] == "queued"


