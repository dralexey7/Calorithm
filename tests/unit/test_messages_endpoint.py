@pytest_asyncio.fixture()
async def api_client_with_inmemory_bus():
    """
    ASGI test client for api-core where:
    - DB probe is overridden with a no-op (unit test, no real Postgres needed)
    - MessageBus is overridden with InMemoryBus (no real Redis needed)

    Returns (client, bus) so tests can inspect what was published.
    """
    from apps.api_core.bus_provider import get_bus
    from apps.api_core.health import get_db_probe
    from apps.api_core.main import app
    from core.bus import InMemoryBus

    bus = InMemoryBus()

    async def _noop_db_probe() -> None:
        return None

    def _db_probe_dep():
        return _noop_db_probe

    def _bus_dep():
        return bus

    app.dependency_overrides[get_db_probe] = _db_probe_dep
    app.dependency_overrides[get_bus] = _bus_dep

    async with AsyncClient(transport=ASGITransport(app=app), base_url="http://test") as client:
        yield client, bus

    app.dependency_overrides.clear()


