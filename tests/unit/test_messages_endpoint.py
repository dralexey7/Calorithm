"""
Unit tests for POST /v1/messages (api-core) — C2-T05.

Verifies that the endpoint:
  - publishes exactly one ProcessingTask to tasks.processing via the bus
  - returns {task_id, status='queued'} with the same task_id
  - returns 422 for structurally invalid bodies (missing required fields)
  - guarantees user_id is populated (stub resolve — Q-C2-3)

The MessageBus is replaced with InMemoryBus via DI override so no real
broker is needed. The DB probe is also overridden to avoid needing Postgres.

LLM/OFF are not involved in C2 — nothing to mock there.
"""

